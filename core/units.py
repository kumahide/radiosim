"""
units.py
========
人が読む数値表記（距離・F1 遮蔽率）の単一ソース。純関数・副作用ゼロ。
GUI・ネットワーク・ファイル I/O を一切持たない（models.py / coords.py と同じ制約）。

方針（2.5a1 / I-014）:
  - **内部計算は km 据え置き**。ITU-R の式が dB/km 系（models.py の比減衰量・
    酸素吸収）で、models.py は副作用ゼロの純コアなので触らない。
  - **換算は表示層のみ**＝人が読む距離はすべて m に統一する。実用距離が 20km
    程度で標高軸が m である以上、距離だけ km は読みづらい（DEM 10m 精度・
    机上スクリーニングという前提とも m のほうが整合する）。
  - **m/km の切替は設けない**。coord_format の DD/DMS は「表記の好み」だが、
    距離は「単位の一貫性」なので固定が正しい（設計哲学⑤＝増やすより削る）。

なぜ独立モジュールなのか:
  以前は距離書式が map_graphics.distance_text（PIL 描画モジュール）と
  report.py / views/graph.py のインライン f-string に散在していた。置き場が
  無いと次の距離表示追加でまた散るので、**表示単位の整形をここ 1 箇所へ**
  集約する（設計哲学⑦＝単一源泉の精神）。
"""

KM_TO_M = 1000.0


def km_to_m(km):
    """km を m へ換算する（丸めない生値）。

    スカラーだけでなく numpy 配列も通す（グラフの距離軸をまとめて換算するため）。
    numpy に依存させたくないので乗算だけで書き、型は呼び出し側のものが返る。
    """
    return km * KM_TO_M


def format_distance(km: float, *, unit: bool = True) -> str:
    """距離 [km] を人が読む m 表記へ整形する（例: 20.153 → ``20,153 m``）。

    桁区切りを入れるのは**人が読む面だけ**（GUI パネル・HTML レポート・地図
    バッジ）。CSV など機械可読の出力には :func:`csv_distance` を使うこと。

    Args:
        km:   距離 [km]
        unit: 単位 ``m`` を付けるか（表の列見出しに単位がある場合は False）
    """
    m = round(float(km) * KM_TO_M)
    text = f"{m:,}"
    return f"{text} m" if unit else text


def format_spacing(spacing_m: float) -> str:
    """標本間隔 [m] を人が読む表記へ整形する（例: 9.14 → ``9.1``・単位なし）。

    ⚠️ **`format_distance` を使い回さない**（I-069）＝あちらは経路長を m 整数へ
    丸める（20,153 m）。標本間隔は **1 m 未満から数百 m まで**動き、しかも
    「高（約 5 m）を選んだのに実効 9.1 m」という**張り付きの検出そのもの**が
    用途なので、整数に丸めると見るべき差が消える。単位はラベル側が持つ。
    """
    value = float(spacing_m)
    return f"{value:.1f}" if value < 100 else f"{round(value):,}"


def csv_distance(km: float, *, decimals: int = 0) -> str:
    """距離 [km] を CSV 用の m 値へ整形する（桁区切りなし・単位なし）。

    表計算ソフトが数値として読めることが要件なので、``,`` は入れない。
    ``decimals`` は分解能の主張＝地形断面のように 0.1m 刻みを保ちたい面でだけ
    増やす（リンクバジェットの距離は m 整数で足りる）。
    """
    m = float(km) * KM_TO_M
    if decimals <= 0:
        return f"{round(m)}"
    return f"{m:.{decimals}f}"


# ============================================================
# F1 遮蔽率（2.5a3 / I-018）
# ------------------------------------------------------------
# models.calculate_propagation の blocked_ratio は「フレネル第1ゾーン半径に対して
# 障害物がどれだけ食い込んでいるか」で、**上限が無い**（深い山越えでは 7000% に
# なる＝実測）。これは侵入深さであって率ではないので、「率(%)」と名乗って出す面
# では 100% で頭打ちにする＝100% は「完全遮蔽」の意味。
#
# ⚠️ 打ち切るのは表示だけで **models の値は生のまま**（環境損失は既に
# `min(blocked_ratio, 100.0)` で内部的に扱っており、計算は生値の情報を使える）。
# ✅ **生の侵入深さは「×F1」という別の量として足した**（3.0a1 / I-077）＝下の
# `format_f1_depth` / `csv_f1_depth`。頭打ち自体は残す（率が 2200% と出るほうが
# 読めない）＝**打ち切った率と、打ち切る前の深さを、別の単位で並べる**形にした。
# ============================================================

BLOCKED_RATIO_MAX = 100.0


def format_blocked_ratio(pct: float, *, unit: bool = True) -> str:
    """F1 遮蔽率 [%] を人が読む表記へ整形する（100% で頭打ち）。

    Args:
        pct:  models の blocked_ratio（上限なしの生値）
        unit: 単位 ``%`` を付けるか（列見出しに単位がある表では False）
    """
    v = min(float(pct), BLOCKED_RATIO_MAX)
    return f"{v:.1f} %" if unit else f"{v:.1f}"


def csv_blocked_ratio(pct: float) -> str:
    """F1 遮蔽率 [%] を CSV 用へ整形する（100% で頭打ち・単位なし）。

    表示と CSV で値が食い違うほうが混乱するので、CSV も同じ上限にする
    （生の侵入深さは別列＝:func:`csv_f1_depth` が持つ）。
    """
    return format_blocked_ratio(pct, unit=False)


# ============================================================
# F1 侵入深さ（3.0a1 / I-077）
# ------------------------------------------------------------
# 「100%」が *ちょうど完全遮蔽* と *深く突き抜けている* の 2 つの意味を持つのが
# I-077 の争点だった（B-032 の発散は 3.0a1 で塞いだので、**発散の印としては
# 要らない**）。⇒ **率とは単位の違う量として足す**＝F1 半径の何倍まで障害物が
# 食い込んでいるか。単位が違えば、読み手が 2 つの列を取り違えない。
#
# ⚠️ **率(%) を 2 列並べない**のが処方の芯（`f1_pct` と `f1_pct_raw` にすると、
# どちらを読むかの迷いが残る）。CSV の列名も単位を含む（`f1_depth_x`）＝
# 出力契約の規約 3「単位を変えるなら列名も変える」と同じ考え方。
# ============================================================

#: 侵入深さの単位（画面・レポートの単位欄と、CSV 列名の接尾辞 `_x` の出所）。
F1_DEPTH_UNIT = "×F1"

#: 侵入深さの小数桁。0.01 ×F1 ＝ 1% 相当で、率の 0.1% よりは粗いが、
#: **この量が意味を持つのは 1.0 を超えてから**なので細かさより桁の少なさを取る。
_F1_DEPTH_DECIMALS = 2


def f1_depth(pct: float) -> float:
    """F1 遮蔽率の生値 [%] を侵入深さ [×F1] へ換算する（丸めない生値）。

    `models.blocked_ratio` は `侵入深さ / F1 半径 * 100` なので、100 で割ると
    **F1 半径の倍数**へ戻る（7109.9 % → 71.099 ×F1）。
    """
    return float(pct) / 100.0


def format_f1_depth(pct: float, *, unit: bool = True) -> str:
    """F1 侵入深さを人が読む表記へ整形する（**頭打ちしない**）。

    Args:
        pct:  models の blocked_ratio（上限なしの生値・単位は %）
        unit: 単位 ``×F1`` を付けるか（列見出しに単位がある表では False）
    """
    v = f1_depth(pct)
    text = f"{v:.{_F1_DEPTH_DECIMALS}f}"
    return f"{text} {F1_DEPTH_UNIT}" if unit else text


def csv_f1_depth(pct: float) -> str:
    """F1 侵入深さを CSV 用へ整形する（頭打ちなし・単位なし）。"""
    return format_f1_depth(pct, unit=False)


# ============================================================
# 損失・レベルの有効桁（3.0a1 / ロードマップ §3.0 の 9）
# ------------------------------------------------------------
# **0.01 dB 刻みは、持っていない精度の主張**だった。DEM の水平解像度は 5〜10m・
# 標高そのものにも数 m の誤差があり、植生高は経路一律の仮定値、環境損失は区分
# 選択の経験値である。⇒ 桁を 0.1 dB へ落とす（画面パネルは元から 0.1 dB で、
# **成果物だけが 2 桁を名乗っていた**＝面によって精度の主張が違っていた）。
#
# ⚠️ **CSV も同じ桁にする**（ユーザー決定 2026-08-26）＝人が読む面と機械が読む面で
# 桁が食い違うほうが、後から説明できない。**書式は出力契約**（`core/output_contract.py`
# 規約 3）なので、CHANGELOG と公開文書の両方に書式変更として書く。
#
# 🔑 **単位は変えていないので列名も変えない**（規約 3 が列名の変更を要求するのは
# *単位*を変えるとき）。桁だけの変更は、数値として読む相手には黙って通る。
# ============================================================

#: 損失・レベル（dB / dBm / dBi）の小数桁。**面をまたいで 1 つ**。
DB_DECIMALS = 1

#: 表示上の 1 刻み（0.1 dB）。**「差を出すかどうか」の境目もここから引く**
#: ＝桁を動かしたのに閾値を据え置くと `(+0.0)` のような中身のない差が出る。
DB_VISIBLE_STEP = 10.0 ** -DB_DECIMALS


def format_db(value: float, *, signed: bool = False, unit: str = "") -> str:
    """損失・レベルを人が読む表記へ整形する（0.1 dB 刻み）。

    Args:
        value:  dB / dBm / dBi の値
        signed: 正号を明示するか（マージンのように符号そのものが読みどころの量）
        unit:   単位を付けるなら文字列（``"dB"`` / ``"dBm"``）。列見出しが単位を
                持つ表では空にする。
    """
    sign = "+" if signed else ""
    text = f"{float(value):{sign}.{DB_DECIMALS}f}"
    return f"{text} {unit}" if unit else text


def csv_db(value: float) -> str:
    """損失・レベルを CSV 用へ整形する（単位なし・桁は表示と同じ）。

    表示と CSV で桁が食い違うほうが混乱するので、**同じ 1 つの桁**を通す
    （符号は付けない＝負値は負値のまま数値として読める）。
    """
    return format_db(value)
